#!/usr/bin/env python3
"""Structural quality checks for Aptitude Beacon's original ASVAB practice bank.

Run: python tools/audit_question_bank.py
These checks do not replace editorial review of answer correctness.
"""
import collections
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "practice.html"
REPORT = ROOT / "QUESTION_BANK_AUDIT.md"

def run():
    source = SOURCE.read_text(encoding="utf-8")
    match = re.search(r"const QUESTIONS=(\[.*?\]);", source, re.S)
    if not match:
        raise RuntimeError("Question bank array not found")
    questions = json.loads(match.group(1))
    failures = []
    seen_ids = set()
    repeated = collections.defaultdict(list)
    subjects = collections.Counter()
    for q in questions:
        qid = q.get("id", "<missing>")
        subj = q.get("subject", "<missing>")
        subjects[subj] += 1
        if qid in seen_ids: failures.append(f"{qid}: duplicate ID")
        seen_ids.add(qid)
        opts = q.get("options")
        ans = q.get("answer")
        if not isinstance(opts, list) or len(opts) != 4:
            failures.append(f"{qid}: expected four choices")
        elif not isinstance(ans, int) or not (0 <= ans < len(opts)):
            failures.append(f"{qid}: invalid answer index")
        elif len(set(str(o).strip() for o in opts)) != 4:
            failures.append(f"{qid}: duplicate answer choices")
        if not q.get("explanation") or len(q["explanation"].strip()) < 15:
            failures.append(f"{qid}: missing/short explanation")
        if not isinstance(q.get("q"), str) or not q["q"].strip():
            failures.append(f"{qid}: missing prompt")
        repeated[(subj,q.get("q", ""))].append(qid)
    count = len(questions)
    duplicate_groups = [(subj,prompt,ids) for (subj,prompt),ids in repeated.items() if len(ids)>1]
    note = [
        "# Question bank structural audit",
        "",
        "Generated by `python tools/audit_question_bank.py`. This is a **structural check only**, not a claim of expert answer review.",
        "",
        f"- Questions: **{count}**",
        f"- Unique IDs: **{len(seen_ids)}**",
        f"- Broken answer index, duplicate choice, or missing explanation findings: **{len(failures)}**",
        f"- Repeated prompt groups: **{len(duplicate_groups)}** (some graphical prompts legitimately share text; inspect their distinct diagrams)",
        "",
        "## Coverage",
        "",
        "| Subject | Items |",
        "|---|---:|",
    ]
    for subject,amount in sorted(subjects.items()):
        note.append(f"| {subject} | {amount} |")
    note += [
        "",
        "## Findings requiring editorial review",
        "",
        "- Much of the initial question bank uses template-driven examples. Review for variety, plausible distractors, difficulty, and clarity.",
        "- Graphical Assembling Objects items reuse written directions. Their visual fields must be compared rather than counting identical text as duplicates.",
        "- Repeated non-spatial prompts should be checked for intentional variation and corrected where needed.",
        "- The answer keys in the bank have **not** been fully validated by subject experts.",
        "- Practice percentages must never be represented as official AFQT scores.",
        "",
        "## Duplicate question prompts outside Assembling Objects",
        "",
    ]
    non_spatial = [(s,p,ids) for s,p,ids in duplicate_groups if s != "Assembling Objects"]
    if not non_spatial: note.append("None.")
    for subj,prompt,ids in non_spatial:
        note.append(f"- {subj}: {', '.join(ids)} — {prompt[:150]}")
    note += ["", "## Structural failures", ""]
    note += [f"- {item}" for item in failures] or ["None detected."]
    note.append("")
    REPORT.write_text("\n".join(note),encoding="utf-8")
    print(f"Questions={count}; subjects={len(subjects)}; uniqueIDs={len(seen_ids)}; failures={len(failures)}; duplicate_prompt_groups={len(duplicate_groups)}")
    for failure in failures[:20]:print("FAIL",failure)
    if failures:
        raise SystemExit(1)
if __name__ == "__main__": run()
